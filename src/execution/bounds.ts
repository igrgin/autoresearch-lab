// Execution facts only. Run lifecycle, reservations, acceptance and counters retain
// their #16 owners. Time is elapsed milliseconds in one identified kernel boot.
export const PHASES = ['preparation', 'agent', 'tool', 'repair', 'compilation', 'training',
  'periodic_validation', 'final_evaluation', 'publication', 'cleanup', 'transfer'] as const;
export type Phase = typeof PHASES[number];
export interface ClockReading { bootId: string; ms: number }
export interface BoundPolicy {
  version: 1; phaseMs: Record<Phase, number>; attemptMs: number; trainingMs: number;
  cancellationMs: number; supervisorMs: number;
}
const minute = 60_000;
// This is an execution profile, not a run-time ceiling or a provider billing limit.
// The configured training duration is unchanged. Adapters persist the resolved
// profile with the operation before dispatch; missing/invalid fields fail closed.
export function defaultBoundPolicy(trainingMs: number): BoundPolicy {
  return validatePolicy({ version: 1, trainingMs, attemptMs: trainingMs + 120 * minute,
    cancellationMs: 10_000, supervisorMs: 15_000,
    phaseMs: { preparation: 30 * minute, agent: 15 * minute, tool: 5 * minute, repair: 15 * minute,
      compilation: trainingMs, training: trainingMs, periodic_validation: 5 * minute,
      final_evaluation: 15 * minute, publication: 2 * minute, cleanup: 30_000, transfer: 30 * minute } });
}
export class BoundError extends Error {
  constructor(readonly code: 'invalid_input' | 'deadline_exceeded' | 'conflict' | 'unsupported_capability') {
    super(`Execution safeguard: ${code}.`);
  }
}
export function positive(value: number): number {
  if (!Number.isSafeInteger(value) || value <= 0) throw new BoundError('invalid_input');
  return value;
}
export function validatePolicy(policy: BoundPolicy): BoundPolicy {
  if (policy?.version !== 1 || !policy.phaseMs ||
      Object.keys(policy).sort().join() !== 'attemptMs,cancellationMs,phaseMs,supervisorMs,trainingMs,version' ||
      Object.keys(policy.phaseMs).sort().join() !== [...PHASES].sort().join()) throw new BoundError('invalid_input');
  for (const key of ['attemptMs', 'trainingMs', 'cancellationMs', 'supervisorMs'] as const) positive(policy[key]);
  for (const phase of PHASES) positive(policy.phaseMs[phase]);
  return structuredClone(policy);
}
export type BoundReason = 'phase_deadline' | 'attempt_deadline' | 'training_deadline' | 'parent_deadline' |
  'supervisor_lost' | 'cancelled' | 'clock_changed' | 'scope_unobservable' | 'persistence_failed' | 'contact_expired';
export interface BoundReceipt {
  phase: Phase; reason: BoundReason; deadlineMs: number; observedMs: number;
}
export interface BoundSnapshot {
  version: 2; bootId: string; startMs: number; lastMs: number; outerDeadlineMs: number;
  parentDeadlineMs: number; policy: BoundPolicy; phase: Phase; deadlines: Partial<Record<Exclude<Phase, 'periodic_validation'>, number>>;
  validationCalls: Record<string, { startMs: number; deadlineMs: number }>; validationCallId?: string;
  trainingDeadlineMs?: number; trainingCutoff?: BoundReceipt; receipt?: BoundReceipt;
}
// Assigned and persisted by the trusted driver before dispatch, never inferred
// from transitions or regenerated by transport retries.
export function validateCallIdentity(phase: Phase, validationCallId?: string): void {
  if (phase === 'periodic_validation' ? typeof validationCallId !== 'string' ||
      !/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/.test(validationCallId) : validationCallId !== undefined) throw new BoundError('invalid_input');
}
function reading(now: ClockReading): void {
  if (!/^[a-zA-Z0-9-]{1,80}$/.test(now.bootId) || !Number.isFinite(now.ms) || now.ms < 0) throw new BoundError('invalid_input');
}
function deadline(start: number, duration: number): number {
  const result = start + duration;
  if (!Number.isFinite(result) || result > Number.MAX_SAFE_INTEGER) throw new BoundError('invalid_input');
  return result;
}
export class ExecutionBounds {
  #state: BoundSnapshot;
  constructor(policy: BoundPolicy, now: ClockReading, parentDeadlineMs = deadline(now.ms, policy.attemptMs)) {
    reading(now); policy = validatePolicy(policy);
    if (!Number.isFinite(parentDeadlineMs) || parentDeadlineMs <= now.ms || parentDeadlineMs > Number.MAX_SAFE_INTEGER) throw new BoundError('invalid_input');
    this.#state = { version: 2, bootId: now.bootId, startMs: now.ms, lastMs: now.ms,
      outerDeadlineMs: deadline(now.ms, policy.attemptMs), parentDeadlineMs, policy, phase: 'preparation',
      validationCalls: {},
      deadlines: { preparation: Math.min(deadline(now.ms, policy.phaseMs.preparation), parentDeadlineMs, deadline(now.ms, policy.attemptMs)) } };
  }
  // Restore checks immutable deadlines rather than recomputing them from now.
  // The storage owner must reconcile the same operation, never create a replacement.
  static restore(snapshot: BoundSnapshot, now: ClockReading): ExecutionBounds {
    const s = structuredClone(snapshot); reading(now);
    if (!s || Object.keys(s).sort().join() !== ['version','bootId','startMs','lastMs','outerDeadlineMs','parentDeadlineMs','policy','phase','deadlines','validationCalls', ...(s.validationCallId !== undefined ? ['validationCallId'] : []), ...(s.trainingDeadlineMs !== undefined ? ['trainingDeadlineMs'] : []), ...(s.trainingCutoff ? ['trainingCutoff'] : []), ...(s.receipt ? ['receipt'] : [])].sort().join()) throw new BoundError('invalid_input');
    if (s?.version !== 2 || !PHASES.includes(s.phase)) throw new BoundError('invalid_input');
    validateCallIdentity(s.phase, s.validationCallId);
    const bounds = new ExecutionBounds(s.policy, { bootId: s.bootId, ms: s.startMs }, s.parentDeadlineMs);
    if (s.outerDeadlineMs !== bounds.#state.outerDeadlineMs || !Number.isFinite(s.lastMs) || s.lastMs < s.startMs ||
        !s.deadlines || typeof s.deadlines !== 'object' || Array.isArray(s.deadlines) ||
        (s.phase !== 'periodic_validation' && s.deadlines[s.phase] === undefined)) throw new BoundError('invalid_input');
    const cap = Math.min(s.outerDeadlineMs, s.parentDeadlineMs);
    for (const [phase, value] of Object.entries(s.deadlines)) {
      if (!PHASES.includes(phase as Phase) || phase === 'periodic_validation' || !Number.isFinite(value) || value! < s.startMs || value! > cap) throw new BoundError('invalid_input');
    }
    if (s.trainingDeadlineMs !== undefined && (!Number.isFinite(s.trainingDeadlineMs) || s.trainingDeadlineMs < s.startMs || s.trainingDeadlineMs > cap)) throw new BoundError('invalid_input');
    if (!s.validationCalls || typeof s.validationCalls !== 'object' || Array.isArray(s.validationCalls)) throw new BoundError('invalid_input');
    for (const [id, call] of Object.entries(s.validationCalls)) {
      validateCallIdentity('periodic_validation', id);
      if (!call || Object.keys(call).sort().join() !== 'deadlineMs,startMs' || s.trainingDeadlineMs === undefined ||
          !Number.isFinite(call.startMs) || call.startMs < s.startMs || call.startMs > s.lastMs ||
          call.startMs >= s.trainingDeadlineMs || call.deadlineMs !== Math.min(deadline(call.startMs, s.policy.phaseMs.periodic_validation), cap, s.trainingDeadlineMs)) throw new BoundError('invalid_input');
    }
    if (charged(s.phase) && s.trainingDeadlineMs === undefined ||
        s.validationCallId !== undefined && !Object.hasOwn(s.validationCalls, s.validationCallId)) throw new BoundError('invalid_input');
    for (const receipt of [s.receipt, s.trainingCutoff]) {
      if (receipt) validateReceipt(receipt);
    }
    bounds.#state = s; bounds.inspect(now); return bounds;
  }
  snapshot(): BoundSnapshot { return structuredClone(this.#state); }
  inspect(now: ClockReading): BoundReceipt | undefined {
    reading(now); const s = this.#state;
    if (s.receipt) return { ...s.receipt };
    if (now.bootId !== s.bootId || now.ms < s.lastMs) return this.expire('clock_changed', now, s.lastMs);
    s.lastMs = now.ms;
    const limits: [number, BoundReason][] = [[s.outerDeadlineMs, 'attempt_deadline'], [s.parentDeadlineMs, 'parent_deadline']];
    if (charged(s.phase) && s.trainingDeadlineMs !== undefined) limits.push([s.trainingDeadlineMs, 'training_deadline']);
    limits.push([this.phaseDeadline(), 'phase_deadline']);
    limits.sort((a, b) => a[0] - b[0]);
    if (now.ms >= limits[0][0]) {
      if (limits[0][1] === 'training_deadline') return { phase: s.phase, reason: 'training_deadline', deadlineMs: limits[0][0], observedMs: now.ms };
      return this.expire(limits[0][1], now, limits[0][0]);
    }
  }
  private phaseDeadline(): number {
    const s = this.#state;
    return s.phase === 'periodic_validation' ? s.validationCalls[s.validationCallId!].deadlineMs : s.deadlines[s.phase]!;
  }
  enter(phase: Phase, now: ClockReading, validationCallId?: string): number {
    if (!PHASES.includes(phase)) throw new BoundError('invalid_input');
    validateCallIdentity(phase, validationCallId);
    if (this.inspect(now)) throw new BoundError('deadline_exceeded');
    const s = this.#state;
    if (s.trainingCutoff && charged(phase)) throw new BoundError('deadline_exceeded');
    if (s.trainingDeadlineMs !== undefined && !s.trainingCutoff && !charged(phase)) throw new BoundError('conflict');
    if (charged(phase) && s.trainingDeadlineMs === undefined) {
      s.trainingDeadlineMs = Math.min(deadline(now.ms, s.policy.trainingMs), s.outerDeadlineMs, s.parentDeadlineMs);
    }
    s.phase = phase;
    if (phase === 'periodic_validation') {
      s.validationCallId = validationCallId!;
      s.validationCalls[validationCallId!] ??= { startMs: now.ms, deadlineMs: Math.min(deadline(now.ms, s.policy.phaseMs[phase]), s.outerDeadlineMs, s.parentDeadlineMs, s.trainingDeadlineMs!) };
    } else {
      delete s.validationCallId;
      s.deadlines[phase] ??= Math.min(deadline(now.ms, s.policy.phaseMs[phase]), s.outerDeadlineMs, s.parentDeadlineMs,
        charged(phase) ? s.trainingDeadlineMs! : Infinity);
    }
    if (this.inspect(now)) throw new BoundError('deadline_exceeded');
    return this.phaseDeadline();
  }
  // Called by the guardian only after the entire training subtree is fenced and
  // observed empty. Eligible sealed checkpoint selection remains evaluator-owned.
  trainingStopped(cutoff: BoundReceipt, now: ClockReading): void {
    const s = this.#state;
    if (s.receipt || cutoff.reason !== 'training_deadline' || cutoff.deadlineMs !== s.trainingDeadlineMs || now.ms < cutoff.deadlineMs) throw new BoundError('conflict');
    s.trainingCutoff = { ...cutoff }; s.phase = 'final_evaluation';
    delete s.validationCallId;
    s.deadlines.final_evaluation ??= Math.min(deadline(now.ms, s.policy.phaseMs.final_evaluation), s.outerDeadlineMs, s.parentDeadlineMs);
    this.inspect(now);
  }
  expire(reason: BoundReason, now: ClockReading, at = now.ms): BoundReceipt {
    reading(now);
    this.#state.receipt ??= { phase: this.#state.phase, reason, deadlineMs: at, observedMs: now.ms };
    return { ...this.#state.receipt };
  }
}
const REASONS: readonly BoundReason[] = ['phase_deadline', 'attempt_deadline', 'training_deadline', 'parent_deadline',
  'supervisor_lost', 'cancelled', 'clock_changed', 'scope_unobservable', 'persistence_failed', 'contact_expired'];
function charged(phase: Phase): boolean { return ['compilation', 'training', 'periodic_validation'].includes(phase); }

// Contact authorizes future admission only. It cannot extend any work deadline.
export class ContactAuthority {
  #expiry: number; #lastMs: number; #sequence = 0; #challenge?: { sequence: number; expires: number }; #latched = false;
  constructor(private readonly epoch: number, private readonly bootId: string, nowMs: number) {
    positive(epoch); reading({ bootId, ms: nowMs }); this.#expiry = nowMs + 30_000; this.#lastMs = nowMs;
  }
  allowed(now: ClockReading): boolean {
    reading(now);
    if (now.bootId !== this.bootId || now.ms < this.#lastMs || now.ms >= this.#expiry) this.#latched = true;
    this.#lastMs = now.ms;
    return !this.#latched;
  }
  challenge(now: ClockReading): { sequence: number; expires: number } {
    if (!this.allowed(now)) throw new BoundError('deadline_exceeded');
    this.#challenge = { sequence: ++this.#sequence, expires: Math.min(now.ms + 5_000, this.#expiry) };
    return { ...this.#challenge };
  }
  renew(epoch: number, sequence: number, now: ClockReading): void {
    if (!this.allowed(now) || epoch !== this.epoch || !this.#challenge || this.#challenge.sequence !== sequence || now.ms >= this.#challenge.expires) {
      throw new BoundError('conflict');
    }
    this.#challenge = undefined; this.#expiry = now.ms + 30_000;
  }
}

export function validateReceipt(receipt: BoundReceipt): void {
  if (!receipt || Object.keys(receipt).sort().join() !== 'deadlineMs,observedMs,phase,reason' ||
      !PHASES.includes(receipt.phase) || !REASONS.includes(receipt.reason) ||
      !Number.isFinite(receipt.deadlineMs) || !Number.isFinite(receipt.observedMs) || receipt.deadlineMs < 0 || receipt.observedMs < 0) throw new BoundError('invalid_input');
}
